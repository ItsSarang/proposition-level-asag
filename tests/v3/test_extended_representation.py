# Structural test: DependencyRelation extended attributes
def test_extended_attributes_in_dependency_relation(parser, triple_extractor):
    """Verify DependencyRelation contains and populates extended attributes."""
    text = "The compiler quickly generates machine code from source files."
    sent = parser.parse_sentence(text)
    triples = triple_extractor.extract(sent)

    assert triples.relation_count >= 1
    rel = triples.canonical_relations[0]

    assert hasattr(rel, "indirect_object")
    assert hasattr(rel, "prepositional_arguments")
    assert hasattr(rel, "predicate_modifiers")
    assert hasattr(rel, "subject_modifiers")
    assert hasattr(rel, "object_modifiers")

    # Predicate modifier 'quickly'
    assert "quickly" in rel.predicate_modifiers
    # Object modifier 'machine' on 'code'
    assert "machine" in rel.object_modifiers
    # Prepositional argument 'from' -> 'file'
    assert any(prep == "from" and pobj == "file" for prep, pobj in rel.prepositional_arguments)

    # Serialization test
    d = rel.to_dict()
    assert "predicate_modifiers" in d
    assert "object_modifiers" in d
    assert "prepositional_arguments" in d


# Cross-slot configuration flag test
def test_triple_matcher_cross_slot_flag():
    """Verify TripleMatcher default enable_cross_slot=False preserves strict classical matching."""
    strict_matcher = TripleMatcher()
    assert strict_matcher.enable_cross_slot is False

    flexible_matcher = TripleMatcher(enable_cross_slot=True)
    assert flexible_matcher.enable_cross_slot is True

    # Reference has preposition, student has direct object
    r1 = DependencyRelation(
        subject="system", predicate="simulate", object="behaviour",
        subject_lemma="system", predicate_lemma="simulate", object_lemma="behaviour",
        relation_type="SPO", source_dependency_relations=("nsubj", "dobj"),
        subject_index=0, predicate_index=1, object_index=2,
        prepositional_arguments=(("of", "portion"),),
    )
    s1 = DependencyRelation(
        subject="system", predicate="simulate", object="portions",
        subject_lemma="system", predicate_lemma="simulate", object_lemma="portion",
        relation_type="SPO", source_dependency_relations=("nsubj", "dobj"),
        subject_index=0, predicate_index=1, object_index=2,
    )

    strict_res = strict_matcher.match([r1], [s1])
    flexible_res = flexible_matcher.match([r1], [s1])

    # In strict mode, behaviour vs portions produces raw similarity (~0.20)
    assert strict_res.matched_relations[0].object_similarity == pytest.approx(0.20, abs=0.05)
    # In flexible mode, cross-slot matching aligns portions with of portions (~0.90)
    assert flexible_res.matched_relations[0].object_similarity == pytest.approx(0.90, abs=0.05)
    assert flexible_res.matched_relations[0].triple_score > strict_res.matched_relations[0].triple_score
