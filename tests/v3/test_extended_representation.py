# Case 1: Exact match
def test_case_1_exact_match(pipeline):
    """Verify identical sentence produces 1.0 score and exact match."""
    q = "What is a primary key?"
    ref = "A primary key uniquely identifies each record in a table."
    stu = "A primary key uniquely identifies each record in a table."

    res = pipeline.evaluate(q, ref, stu)
    assert res.matched_propositions_count == 1
    assert res.reference_propositions_count == 1
    assert res.unmatched_student_propositions_count == 0
    assert res.base_score_normalized == 1.0
    assert res.final_score_scaled == 5.0
    assert res.explanation_trace.matched_items[0].entailment_status == "ENTAILS"
    assert res.explanation_trace.matched_items[0].match_score == 1.0


